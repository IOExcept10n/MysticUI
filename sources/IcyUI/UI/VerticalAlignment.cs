namespace Icy.UI
{
    /// <summary>
    /// Defines the vertical alignment of a UI element within its parent container.
    /// </summary>
    public enum VerticalAlignment
    {
        /// <summary>
        /// Aligns the UI element to the top of the parent container.
        /// </summary>
        Top,

        /// <summary>
        /// Centers the UI element vertically within the parent container.
        /// </summary>
        Center,

        /// <summary>
        /// Aligns the UI element to the bottom of the parent container.
        /// </summary>
        Bottom,

        /// <summary>
        /// Stretches the UI element to fill the available vertical space of the parent container.
        /// </summary>
        Stretch,
    }
}
